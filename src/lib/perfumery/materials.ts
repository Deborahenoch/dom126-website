const byId = new Map(materials.map((m) => [m.id, m]));

export function getMaterial(id: string): Material | undefined {
  return byId.get(id);
}

/**
 * Tolerant lookup: matches id, exact name, chemical name or common alias.
 * Handy when importing formulas written by hand.
 */
export function findMaterial(query: string): Material | undefined {
  const q = query.trim().toLowerCase();
  if (!q) return undefined;
  return (
    byId.get(q) ??
    materials.find(
      (m) =>
        m.name.toLowerCase() === q ||
        m.chemicalName?.toLowerCase() === q ||
        m.id === q.replace(/[\s()]+/g, "-"),
    ) ??
    materials.find(
      (m) =>
        m.name.toLowerCase().includes(q) ||
        q.includes(m.name.toLowerCase()) ||
        m.chemicalName?.toLowerCase().includes(q),
    )
  );
}

export const materialCount = materials.length;

/** Naturals vs synthetics, for the atlas summary. */
export const originBreakdown = materials.reduce<Record<string, number>>((acc, m) => {
  acc[m.origin] = (acc[m.origin] ?? 0) + 1;
  return acc;
}, {});

/**
 * Materials that cannot legally or practically appear in a modern EU-market
 * fine fragrance. The vault flags these hard, because almost every classic
 * reconstruction in `classics.ts` contains at least one.
 */
export const blockedMaterials = materials.filter(
  (m) =>
    m.regulatory.status === "banned-eu-cosmetics" ||
    (m.regulatory.status === "restricted" && /CITES|prohibited|Banned|whale|Beaver/i.test(m.regulatory.note ?? "")),
);

/** EU Annex III declarable allergens present in the palette. */
export const euAllergens = materials.filter((m) => m.regulatory.euAllergen);

